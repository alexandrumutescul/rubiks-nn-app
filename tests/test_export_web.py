def test_net_layout_matches_print_net(exported):
    """net_pos places every facelet where rubiks.cube.print_net draws it (U on top, L F R B, D below)."""
    t = exported[1]
    assert t["net_size"] == [9, 12]
    assert t["facelet_names"][0] == "U1" and t["facelet_names"][53] == "B9" and len(t["facelet_names"]) == 54
    assert len({tuple(p) for p in t["net_pos"]}) == 54
    state = cube.apply_sequence(cube.SOLVED, np.random.default_rng(3).integers(0, 18, 40).tolist())
    grid = {}
    for r, line in enumerate(cube.print_net(state).splitlines()):
        tokens = line.split()
        cols = range(3, 6) if len(tokens) == 3 else range(12)
        for c, tok in zip(cols, tokens, strict=True):
            grid[(r, c)] = tok
    assert len(grid) == 54
    for i, (r, c) in enumerate(t["net_pos"]):
        assert grid[(r, c)] == t["face_names"][state[i]], (i, r, c)


def test_scramble_filter_matches_generator(exported):
    t = exported[1]
    f = t["scramble_filter"]
    assert f["rule"] == ("face(t) != face(t-1); if face(t-2) and face(t-1) are opposite, "
                         "face(t) differs from both")
    assert f["opposite"] == [[0, 3], [1, 4], [2, 5]]
    # rubiks.sampling treats faces a != b as opposite iff a % 3 == b % 3: the exported pairs are exactly those.
    pairs = {frozenset(p) for p in f["opposite"]}
    assert pairs == {frozenset((a, b)) for a in range(6) for b in range(6) if a != b and a % 3 == b % 3}


