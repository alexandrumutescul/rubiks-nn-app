REPO = Path(__file__).resolve().parent.parent
SEED = 20261012


def run_cli(out: Path, seed: int = SEED) -> str:
    cmd = [sys.executable, "-m", "rubiks.export_web", "--out", str(out), "--seed", str(seed)]
    res = subprocess.run(cmd, cwd=REPO, capture_output=True, text=True, timeout=120)
    assert res.returncode == 0, res.stderr
    assert "uniform states" in res.stdout
    return out.read_text(encoding="ascii")


