def body_lines(text: str) -> list[str]:
    return [line for line in text.splitlines() if not line.startswith("//")]


def test_file_layout(exported):
    text = exported[0]
    lines = text.splitlines()
    comments = [line for line in lines if line.startswith("//")]
    assert lines[0].startswith("// cube-tables.js: GENERATED by")
    assert len(comments) == 2 and lines[:2] == comments
    assert "utc" not in text.lower()  # no timestamp anywhere: provenance is the git commit and the seed
    code = body_lines(text)
    assert code[0] == "window.CUBE_TABLES = {"
    assert code[-1] == "};"
    assert text.isascii()
    assert 80_000 < len(text) < 200_000  # commit-sized


