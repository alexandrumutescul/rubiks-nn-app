def test_test_vectors_reproduce(exported):
    t = exported[1]
    tv = t["test_vectors"]
    assert len(tv["sequences"]) == 50
    for v in tv["sequences"]:
        assert len(v["moves"]) == 30 and all(0 <= m < 18 for m in v["moves"])
        assert len(v["state"]) == 54
        assert np.array_equal(cube.apply_sequence(cube.SOLVED, v["moves"]), np.array(v["state"]))
    assert len({tuple(v["moves"]) for v in tv["sequences"]}) == 50
    assert tv["identity"] == "R L U2 R L' B2 U2 R2 F2 L2 D2 L2 F2"
    assert cube.is_solved(cube.apply_sequence(cube.SOLVED, cube.parse_moves(tv["identity"])))
    assert tv["orders"] == {"R U": 105, "R U R' U'": 6, "R2 U2": 6}
    for text, order in tv["orders"].items():
        assert cube.perm_order(cube.sequence_perm(cube.parse_moves(text))) == order


def test_uniform_states_valid_and_seeded(exported):
    t = exported[1]
    states = np.array(t["uniform_states"], dtype=np.uint8)
    assert states.shape == (1000, 54)
    for s in states:
        assert cubie.from_facelets(s).is_valid()
    assert len({bytes(s) for s in states}) == 1000
    assert not cube.is_solved_batch(states).any()
    child = np.random.SeedSequence(SEED).spawn(2)[1]
    assert np.array_equal(states, sampling.uniform_random_states(np.random.default_rng(child), 1000))


