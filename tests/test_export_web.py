def scrambled(seed: int = 5, n: int = 25) -> np.ndarray:
    seq = np.random.default_rng(seed).integers(0, 18, size=n).tolist()
    return cube.apply_sequence(cube.SOLVED, seq)


@pytest.mark.parametrize("body,needle", [
    (b"not json", "JSON"),
    (b"[1, 2]", "object"),
    (b'{"x": 1}', "state"),
    (b'{"state": [0, 1]}', "54"),
    (b'{"state": "UUU"}', "54"),
    (b'{"state": [' + b",".join([b"7"] * 54) + b"]}", "0..5"),
    (b'{"state": [' + b",".join([b"true"] * 54) + b"]}", "integers"),
])
def test_solve_rejects_malformed_bodies(body, needle):
    status, payload = serve.handle_solve(body)
    assert status == 400
    assert needle in payload["error"]


def test_solve_rejects_unreachable_state():
    s = cube.SOLVED.copy()
    # twist one corner (URF: U9, R1, F3 = facelets 8, 9, 20) in place
    s[[8, 9, 20]] = s[[20, 8, 9]]
    status, payload = serve.handle_solve(json.dumps({"state": s.tolist()}).encode())
    assert status == 400 and "not reachable" in payload["error"]
    s = cube.SOLVED.copy()
    s[4] = 1  # wrong centre
    status, payload = serve.handle_solve(json.dumps({"state": s.tolist()}).encode())
    assert status == 400 and "invalid state" in payload["error"]


def test_solve_solved_state_returns_no_moves():
    status, payload = serve.handle_solve(json.dumps({"state": cube.SOLVED.tolist()}).encode())
    assert status == 200 and payload["moves"] == []


def test_solve_without_backend_is_501(monkeypatch):
    monkeypatch.setitem(sys.modules, "kociemba", None)  # makes "import kociemba" raise ImportError
    status, payload = serve.handle_solve(json.dumps({"state": scrambled().tolist()}).encode())
    assert status == 501 and payload == {"error": "no solver backend"}


@pytest.fixture(scope="module")
def static_server(tmp_path_factory):
    """A short-lived rubiks.serve handler on 127.0.0.1, port 0, over a temp web dir with symlinks out of it."""
    tmp_path = tmp_path_factory.mktemp("static")
    web = tmp_path / "web"
    web.mkdir()
    (web / "index.html").write_text("<p>INDEX</p>")
    (web / "ok.txt").write_text("INSIDE")
    (web / "app.js").write_text("// js")
    (web / "inner-link.txt").symlink_to(web / "ok.txt")            # symlink staying inside: allowed
    outside = tmp_path / "outside"
    outside.mkdir()
    (outside / "secret.txt").write_text("SECRET")
    (outside / "index.html").write_text("SECRET INDEX")
    (web / "link.txt").symlink_to(outside / "secret.txt")          # file symlink out of the root
    (web / "linkdir").symlink_to(outside, target_is_directory=True)  # directory symlink out of the root
    (web / "sub").mkdir()
    (web / "sub" / "index.html").symlink_to(outside / "index.html")  # directory index file out of the root
    (web / "empty").mkdir()                                         # no index: must not be listed
    handler = functools.partial(serve.Handler, directory=str(web))
    httpd = ThreadingHTTPServer(("127.0.0.1", 0), handler)
    thread = threading.Thread(target=httpd.serve_forever, daemon=True)
    thread.start()

    def request(method, path, body=None, headers=None):
        conn = http.client.HTTPConnection("127.0.0.1", httpd.server_address[1], timeout=10)
        try:
            conn.request(method, path, body=body, headers=headers or {})
            resp = conn.getresponse()
            return resp.status, dict(resp.getheaders()), resp.read()
        finally:
            conn.close()

    try:
        yield request
    finally:
        httpd.shutdown()
        httpd.server_close()
        thread.join(timeout=10)


@pytest.mark.parametrize("path,body", [
    ("/ok.txt", b"INSIDE"), ("/", b"<p>INDEX</p>"), ("/index.html", b"<p>INDEX</p>"),
    ("/inner-link.txt", b"INSIDE"), ("/ok.txt?x=1", b"INSIDE"),
])
def test_static_serves_files_inside_the_root(static_server, path, body):
    status, headers, data = static_server("GET", path)
    assert status == 200 and data == body
    assert headers["Access-Control-Allow-Origin"] == "*"


@pytest.mark.parametrize("method", ["GET", "HEAD"])
@pytest.mark.parametrize("path", [
    "/link.txt", "/linkdir/", "/linkdir/secret.txt", "/linkdir/index.html", "/linkdir", "/sub/",
    "/sub/index.html", "/empty/", "/../outside/secret.txt", "/%2e%2e/outside/secret.txt", "/ok.txt/", "/missing.js",
])
def test_static_refuses_targets_outside_the_root(static_server, method, path):
    status, _, data = static_server(method, path)
    assert status == 404, (method, path, status)
    assert b"SECRET" not in data


def test_static_directory_redirect_and_content_type(static_server):
    status, headers, _ = static_server("GET", "/sub")
    assert status == 301 and headers["Location"] == "/sub/"   # inside the root: redirect, then 404 above
    status, headers, _ = static_server("HEAD", "/app.js")
    assert status == 200 and "javascript" in headers["Content-type"]


def test_http_solve_and_preflight(static_server):
    status, headers, data = static_server("OPTIONS", "/solve")
    assert status == 204 and headers["Access-Control-Allow-Origin"] == "*"
    assert "POST" in headers["Access-Control-Allow-Methods"]
    status, headers, data = static_server("POST", "/solve", json.dumps({"state": cube.SOLVED.tolist()}),
                                          {"Content-Type": "application/json"})
    assert status == 200 and json.loads(data)["moves"] == []
    assert headers["Access-Control-Allow-Origin"] == "*"
    status, _, data = static_server("POST", "/solve", "{", {"Content-Type": "application/json"})
    assert status == 400 and "JSON" in json.loads(data)["error"]
    status, _, _ = static_server("POST", "/other", "{}")
    assert status == 404


def test_solve_with_kociemba_solves():
    pytest.importorskip("kociemba")
    for seed in range(5):
        s = scrambled(seed)
        status, payload = serve.handle_solve(json.dumps({"state": s.tolist()}).encode())
        assert status == 200, payload
        assert payload["solver"] == "kociemba" and payload["verified"] is True
        assert all(isinstance(m, int) and 0 <= m < 18 for m in payload["moves"])
        assert cube.is_solved(cube.apply_sequence(s, payload["moves"]))
